/// Keys as the PC keyboard sends them: XT (set 1) scancodes, with `0xE0` in the high byte for extended keys.
///
/// QEMU's extended key events carry these, so a hardware keyboard reaches the guest as physical keys: modifiers,
/// shortcuts and the guest's own keyboard layout all work, unlike with keysyms that QEMU maps through a US layout.
public enum Scancode {
    public static let leftControl: UInt16 = 0x1D
    public static let leftShift: UInt16 = 0x2A
    public static let leftAlt: UInt16 = 0x38
    public static let leftWindows: UInt16 = 0xE05B

    /// The scancode for a USB HID keyboard usage (page 7), as `UIKey.keyCode` reports it. nil for keys PCs lack.
    public static func forHIDUsage(_ usage: Int) -> UInt16? {
        switch usage {
        case 0x04...0x1D: letters[usage - 0x04]
        case 0x1E...0x26: UInt16(usage - 0x1E + 0x02) // 1 to 9
        case 0x27: 0x0B // 0
        case 0x3A...0x43: UInt16(usage - 0x3A + 0x3B) // F1 to F10
        case 0x59...0x61: keypadDigits[usage - 0x59] // keypad 1 to 9
        default: others[usage]
        }
    }

    /// a to z.
    private static let letters: [UInt16] = [
        0x1E, 0x30, 0x2E, 0x20, 0x12, 0x21, 0x22, 0x23, 0x17, 0x24, 0x25, 0x26, 0x32,
        0x31, 0x18, 0x19, 0x10, 0x13, 0x1F, 0x14, 0x16, 0x2F, 0x11, 0x2D, 0x15, 0x2C,
    ]

    private static let keypadDigits: [UInt16] = [0x4F, 0x50, 0x51, 0x4B, 0x4C, 0x4D, 0x47, 0x48, 0x49]

    private static let others: [Int: UInt16] = [
        0x28: 0x1C, // Return
        0x29: 0x01, // Escape
        0x2A: 0x0E, // Backspace
        0x2B: 0x0F, // Tab
        0x2C: 0x39, // Space
        0x2D: 0x0C, 0x2E: 0x0D, 0x2F: 0x1A, 0x30: 0x1B, 0x31: 0x2B, 0x32: 0x2B, // - = [ ] \ #
        0x33: 0x27, 0x34: 0x28, 0x35: 0x29, 0x36: 0x33, 0x37: 0x34, 0x38: 0x35, // ; ' ` , . /
        0x39: 0x3A, // Caps Lock
        0x44: 0x57, 0x45: 0x58, // F11, F12
        0x46: 0xE037, // Print Screen
        0x47: 0x46, // Scroll Lock
        0x49: 0xE052, 0x4A: 0xE047, 0x4B: 0xE049, // Insert, Home, Page Up
        0x4C: 0xE053, 0x4D: 0xE04F, 0x4E: 0xE051, // Delete, End, Page Down
        0x4F: 0xE04D, 0x50: 0xE04B, 0x51: 0xE050, 0x52: 0xE048, // Right, Left, Down, Up
        0x53: 0x45, // Num Lock
        0x54: 0xE035, 0x55: 0x37, 0x56: 0x4A, 0x57: 0x4E, 0x58: 0xE01C, // keypad / * - + Enter
        0x62: 0x52, 0x63: 0x53, // keypad 0 and .
        0x64: 0x56, // the key left of Z on ISO keyboards
        0x65: 0xE05D, // Menu
        0xE0: 0x1D, 0xE1: 0x2A, 0xE2: 0x38, 0xE3: 0xE05B, // left Control, Shift, Alt, Windows
        0xE4: 0xE01D, 0xE5: 0x36, 0xE6: 0xE038, 0xE7: 0xE05C, // right Control, Shift, Alt, Windows
    ]

    /// The keycode of QEMU's extended key event: extended keys as their low byte with the top bit set.
    static func qemuKeycode(_ scancode: UInt16) -> UInt32 {
        if scancode >> 8 == 0xE0, scancode & 0xFF < 0x7F { return UInt32(scancode & 0xFF) | 0x80 }
        return UInt32(scancode)
    }
}
